import Foundation
import SwiftDebtCore
import SwiftDebtReporting

struct ReportRenderingInput {
    let report: AnalysisReport
    let rankedDebtAnalysis: RankedDebtAnalysis?
    let format: ReportFormat
    let root: URL
    let diagnostics: String
    let profiler: AnalysisProfiler?
}

extension AnalysisService {
    func render(_ input: ReportRenderingInput) throws -> String {
        input.profiler?.begin(.rendering)
        defer { input.profiler?.end(.rendering) }
        if input.format.isDebtReportFormat {
            guard let rankedDebtAnalysis = input.rankedDebtAnalysis else {
                throw AnalysisFailure.invalidConfiguration(
                    "Debt report formats require debtAnalysis configuration")
            }
            return try ReportRenderer().renderDebt(
                rankedDebtAnalysis, format: input.format, graph: input.report.dependencyGraph)
        }
        let base = try ReportRenderer().render(
            input.report, format: input.format, root: input.root.path)
        return input.format == .diagnostics ? base + input.diagnostics : base
    }

    func protectedPaths(for request: AnalysisRequest, workspace: PreparedAnalysis) -> Set<String> {
        var paths = Set(
            workspace.selection.entries.map {
                URL(fileURLWithPath: $0.path).resolvingSymlinksInPath().path
            })
        paths.insert(workspace.configurationURL.resolvingSymlinksInPath().path)
        if let manifest = request.manifestPath {
            paths.insert(URL(fileURLWithPath: manifest).resolvingSymlinksInPath().path)
        }
        return paths
    }

    func writeReport(
        _ rendered: String, request: AnalysisRequest, protectedPaths: inout Set<String>
    ) throws {
        guard let output = request.outputPath else { return }
        let url = URL(fileURLWithPath: output).standardizedFileURL.resolvingSymlinksInPath()
        guard !protectedPaths.contains(url.path), url.pathExtension != "swift" else {
            throw WorkspaceError(
                "Refusing to overwrite a source, configuration, manifest, or Swift file with a "
                    + "report"
            )
        }
        try write(rendered, to: url)
        protectedPaths.insert(url.path)
    }

    func writeProfile(
        _ profile: AnalysisProfile?, request: AnalysisRequest,
        protectedPaths: inout Set<String>
    ) throws {
        guard let profileOutput = request.profileOutputPath, let profile else { return }
        let url = URL(fileURLWithPath: profileOutput).standardizedFileURL.resolvingSymlinksInPath()
        guard !protectedPaths.contains(url.path), url.pathExtension != "swift" else {
            throw WorkspaceError(
                "Refusing to overwrite a source, configuration, manifest, report, or Swift file "
                    + "with a profile"
            )
        }
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        let data = try encoder.encode(profile)
        try FileManager.default.createDirectory(
            at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        try data.write(to: url, options: .atomic)
        protectedPaths.insert(url.path)
    }

    func exitStatus(
        report: AnalysisReport,
        rankedDebtAnalysis: RankedDebtAnalysis?,
        validation: WorkspaceDebtValidation?,
        failOnViolation: Bool
    ) -> Int32 {
        guard report.complete else { return 2 }
        let validationFailed = debtValidationFailed(validation, analysis: rankedDebtAnalysis)
        return (failOnViolation && report.hasViolations) || validationFailed ? 1 : 0
    }

    func writeStamp(_ path: String?, status: Int32, protectedPaths: Set<String>) throws {
        guard let path, status == 0 else { return }
        let url = URL(fileURLWithPath: path).standardizedFileURL.resolvingSymlinksInPath()
        let content = "// Generated by SwiftDebt: analysis completed. No runtime declarations.\n"
        guard url.lastPathComponent == "SwiftDebt.analysis.swift",
            !protectedPaths.contains(url.path)
        else {
            throw WorkspaceError(
                "Invalid build stamp path; expected an unprotected SwiftDebt.analysis.swift")
        }
        if FileManager.default.fileExists(atPath: url.path) {
            guard try String(contentsOf: url, encoding: .utf8) == content else {
                throw WorkspaceError("Refusing to replace an existing non-SwiftDebt stamp")
            }
        }
        try write(content, to: url)
    }
}
